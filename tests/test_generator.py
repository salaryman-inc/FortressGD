"""Deterministic dialect.gen.h: data only, same inputs => same salt/masks."""

from __future__ import annotations

import tempfile
import unittest
from pathlib import Path

from fortressgd.core.kdf import fgd_kdf_1
from fortressgd.core.secret import SECRET_BYTES
from fortressgd.core.shards import decode_shards
from fortressgd.generator.dialect import (
    GENERATOR_VERSION,
    STOCK_PACK_MAGIC,
    derive_dialect_salt,
    derive_index_perm,
    derive_pack_magic,
    derive_shard_masks,
    dialect_material,
    render_dialect_header,
    write_dialect_header,
)
from fortressgd.generator.opcode_map import FGD_OPCODE_COUNT, opcode_map, opcode_unmap


class GeneratorTests(unittest.TestCase):
    def setUp(self) -> None:
        self.secret = bytes(range(SECRET_BYTES))

    def test_identical_inputs_identical_header_and_salt_masks(self) -> None:
        a = render_dialect_header(self.secret, "4.6.2")
        b = render_dialect_header(self.secret, "4.6.2")
        self.assertEqual(a, b)
        self.assertEqual(derive_dialect_salt(self.secret, "4.6.2"), derive_dialect_salt(self.secret, "4.6.2"))
        self.assertEqual(derive_shard_masks(self.secret, "4.6.2"), derive_shard_masks(self.secret, "4.6.2"))
        self.assertEqual(derive_pack_magic(self.secret, "4.6.2"), derive_pack_magic(self.secret, "4.6.2"))
        self.assertEqual(derive_index_perm(self.secret, "4.6.2"), derive_index_perm(self.secret, "4.6.2"))
        self.assertIn("FGD_DIALECT_SALT[16]", a)
        self.assertIn("FGD_SHARD_MASKS[4][8]", a)
        self.assertIn("FGD_SHARDS[4][8]", a)
        self.assertIn("FGD_PACK_MAGIC", a)
        self.assertIn("FGD_INDEX_PERM[4]", a)
        self.assertIn("FGD_OPCODE_MAP[{0}]".format(FGD_OPCODE_COUNT), a)
        self.assertIn("FGD_OPCODE_UNMAP[{0}]".format(FGD_OPCODE_COUNT), a)
        self.assertIn("FGD_PACK_PUBKEY[32]", a)
        self.assertIn("data only", a)
        self.assertNotIn("if (", a)
        self.assertNotIn("for (", a)
        self.assertNotRegex(a, r"[0-9a-fA-F]{64}")
        magic = derive_pack_magic(self.secret, "4.6.2")
        self.assertNotEqual(magic, STOCK_PACK_MAGIC)
        self.assertIn("0x{0:08x}".format(magic), a)

    def test_header_require_pack_signature_flag(self) -> None:
        secret = bytes(range(1, 33))
        off = render_dialect_header(secret, "4.6.2")
        on = render_dialect_header(secret, "4.6.2", require_signature=True)
        self.assertIn("static const uint8_t FGD_REQUIRE_PACK_SIGNATURE = 0;", off)
        self.assertIn("static const uint8_t FGD_REQUIRE_PACK_SIGNATURE = 1;", on)
        self.assertNotIn("FGD_REQUIRE_PACK_SIGNATURE = 1;", off)

    def test_header_shards_round_trip_to_secret(self) -> None:
        salt, masks, shards, did = dialect_material(self.secret, "4.6.2")
        self.assertEqual(decode_shards(shards, masks), self.secret)
        self.assertEqual(len(did), 16)
        self.assertEqual(GENERATOR_VERSION, 2)

    def test_different_tag_or_secret_changes_magic_or_perm(self) -> None:
        salt_a = derive_dialect_salt(self.secret, "4.6.2")
        salt_b = derive_dialect_salt(self.secret, "4.7.2")
        self.assertNotEqual(salt_a, salt_b)
        self.assertNotEqual(fgd_kdf_1(self.secret, salt_a), fgd_kdf_1(self.secret, salt_b))
        header_a = render_dialect_header(self.secret, "4.6.2")
        header_b = render_dialect_header(self.secret, "4.7.2")
        self.assertNotEqual(header_a, header_b)
        magic_a = derive_pack_magic(self.secret, "4.6.2")
        magic_b = derive_pack_magic(self.secret, "4.7.2")
        perm_a = derive_index_perm(self.secret, "4.6.2")
        perm_b = derive_index_perm(self.secret, "4.7.2")
        self.assertTrue(magic_a != magic_b or perm_a != perm_b)
        other = bytes((b + 1) % 256 for b in self.secret)
        magic_c = derive_pack_magic(other, "4.6.2")
        perm_c = derive_index_perm(other, "4.6.2")
        self.assertTrue(magic_a != magic_c or perm_a != perm_c)
        self.assertNotEqual(header_a, render_dialect_header(other, "4.6.2"))

    def test_write_header_and_opcode_map_stub(self) -> None:
        with tempfile.TemporaryDirectory() as tmp:
            path = Path(tmp) / "dialect.gen.h"
            write_dialect_header(path, self.secret, "4.6.2")
            text = path.read_text(encoding="utf-8")
            self.assertTrue(text.startswith("/* generated by fortressgd"))
            self.assertIn("FGD_OPCODE_MAP", text)
            self.assertIn("FGD_PACK_PUBKEY", text)

    def test_opcode_map_is_deterministic_bijection_not_identity(self) -> None:
        a = opcode_map(self.secret, "4.6.2")
        b = opcode_map(self.secret, "4.6.2")
        self.assertEqual(a, b)
        n = FGD_OPCODE_COUNT
        self.assertEqual(set(a.keys()), set(range(n)))
        self.assertEqual(set(a.values()), set(range(n)))
        identity = {i: i for i in range(n)}
        self.assertNotEqual(a, identity)
        other = bytes((x + 1) % 256 for x in self.secret)
        c = opcode_map(other, "4.6.2")
        self.assertNotEqual(a, c)
        self.assertEqual(set(c.values()), set(range(n)))
        inv = opcode_unmap(self.secret, "4.6.2")
        for src, dst in a.items():
            self.assertEqual(inv[dst], src)
        tag_b = opcode_map(self.secret, "4.7.2")
        self.assertEqual(set(tag_b.values()), set(range(n)))


if __name__ == "__main__":
    unittest.main()
