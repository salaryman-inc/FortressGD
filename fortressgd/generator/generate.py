"""Assemble fortressgd_gen.cpp for generator v2 (DESIGN.md §18.3).

The five functions declared in fortressgd_gen_api.h are defined here, each from a
per-build op chain (fortressgd/generator/emit.py). The plaintext values are the
exact outputs of the v1 derivations, so a template built from this file opens the
same packs `fortressgd export` produces: the pack AES key is
FGD-KDF-1(secret, salt), and the magic, index permutation, opcode tables and
public key match dialect.py / opcode_map.py / pack_sign.py.

The key is split into 3-8 pieces, each stored under its own chain in a separately
named array and reassembled in generated order. Function definition order comes
from the code stream too. None of the generated code holds the secret, the salt
or the signing seed; it holds only what the v1 header already did, encoded
differently.
"""

from __future__ import annotations

import struct

from fortressgd.core.kdf import fgd_kdf_1
from fortressgd.core.pack_sign import public_key_for_secret
from fortressgd.core.secret import SECRET_BYTES
from fortressgd.generator.codeseed import CodeStream, derive_code_seed
from fortressgd.generator.dialect import (
    derive_dialect_salt,
    derive_index_perm,
    derive_pack_magic,
)
from fortressgd.generator.emit import emit_decode_fn
from fortressgd.generator.opchain import build_chain
from fortressgd.generator.opcode_map import FGD_OPCODE_COUNT, opcode_perm, opcode_unmap

KEY_LEN = 32
MIN_KEY_PIECES = 3
MAX_KEY_PIECES = 8


def plaintext_values(
    secret: bytes,
    godot_tag: str,
    dialect_seed: bytes | None = None,
    key_epoch: int = 0,
) -> dict:
    """The exact values the generated code must reproduce (the v1 derivations)."""
    if len(secret) != SECRET_BYTES:
        raise ValueError("secret must be {0} bytes".format(SECRET_BYTES))
    salt = derive_dialect_salt(secret, godot_tag, dialect_seed, key_epoch)
    key = fgd_kdf_1(secret, salt)
    magic = derive_pack_magic(secret, godot_tag, dialect_seed)
    perm = derive_index_perm(secret, godot_tag, dialect_seed)
    omap = opcode_perm(secret, godot_tag, dialect_seed)
    ounmap = opcode_unmap(secret, godot_tag, dialect_seed)
    pubkey = public_key_for_secret(secret, godot_tag, dialect_seed)
    if FGD_OPCODE_COUNT > 256:  # pragma: no cover - guards the uint8 packing below
        raise ValueError("opcode count must fit in a byte for the generated tables")
    return {
        "key": key,
        "magic": magic,
        "index_perm": bytes(perm),
        "opcode_map": bytes(omap),
        "opcode_unmap": bytes(ounmap),
        "pubkey": pubkey,
    }


def _decoder(stream: CodeStream, name: str, plain: bytes, info: bytes) -> str:
    inner = CodeStream(stream.read(32), info)
    chain = build_chain(inner, len(plain))
    load_form = inner.randbelow(3)  # shape of the copy that loads the encoded bytes
    return emit_decode_fn(name, plain, chain, load_form)


def render_gen_cpp(
    secret: bytes,
    godot_tag: str,
    dialect_seed: bytes | None = None,
    key_epoch: int = 0,
) -> str:
    """The full fortressgd_gen.cpp text. Deterministic for (secret, tag, seed, epoch)."""
    v = plaintext_values(secret, godot_tag, dialect_seed, key_epoch)
    seed = derive_code_seed(secret, godot_tag, key_epoch)
    stream = CodeStream(seed, b"fortressgd.gen.cpp|" + godot_tag.encode("utf-8"))

    # Split the key into pieces with per-build sizes.
    n_pieces = stream.randrange(MIN_KEY_PIECES, MAX_KEY_PIECES)
    sizes = stream.split_sizes(KEY_LEN, n_pieces)
    offsets = []
    off = 0
    for s in sizes:
        offsets.append(off)
        off += s

    # Build every static decode function. (name, source, caller-site info)
    decoders: list[tuple[str, str]] = []
    key_pieces: list[tuple[str, int]] = []  # (fn name, offset)
    for i, (sz, ofs) in enumerate(zip(sizes, offsets)):
        name = "fgd__k{0}".format(i)
        decoders.append((name, _decoder(stream, name, v["key"][ofs : ofs + sz], b"key%d" % i)))
        key_pieces.append((name, ofs))
    decoders.append(("fgd__magic", _decoder(stream, "fgd__magic", struct.pack("<I", v["magic"]), b"magic")))
    decoders.append(("fgd__perm", _decoder(stream, "fgd__perm", v["index_perm"], b"perm")))
    decoders.append(("fgd__omap", _decoder(stream, "fgd__omap", v["opcode_map"], b"omap")))
    decoders.append(("fgd__ounmap", _decoder(stream, "fgd__ounmap", v["opcode_unmap"], b"ounmap")))
    decoders.append(("fgd__pubkey", _decoder(stream, "fgd__pubkey", v["pubkey"], b"pubkey")))

    # Emit the definitions in seed-chosen order (layout varies per build).
    order = list(range(len(decoders)))
    stream.shuffle(order)

    lines: list[str] = []
    lines.append("/* generated by fortressgd generator v2; do not commit */")
    lines.append('#include "fortressgd_gen_api.h"')
    lines.append("")
    lines.append("#include <cstdint>")
    lines.append("")
    for idx in order:
        lines.append(decoders[idx][1])
        lines.append("")

    # fgd_derive_key: reassemble the pieces into the 32-byte key.
    lines.append("void fgd_derive_key(uint8_t r_key[32]) {")
    for name, ofs in key_pieces:
        lines.append("\t{0}(r_key + {1});".format(name, ofs))
    lines.append("}")
    lines.append("")

    lines.append("uint32_t fgd_pack_magic() {")
    lines.append("\tuint8_t b[4];")
    lines.append("\tfgd__magic(b);")
    lines.append(
        "\treturn (uint32_t)b[0] | ((uint32_t)b[1] << 8) | ((uint32_t)b[2] << 16) | ((uint32_t)b[3] << 24);"
    )
    lines.append("}")
    lines.append("")

    lines.append("void fgd_index_perm(uint8_t r_perm[4]) {")
    lines.append("\tfgd__perm(r_perm);")
    lines.append("}")
    lines.append("")

    lines.append("void fgd_opcode_tables(uint16_t r_map[FGD_OPCODE_COUNT], uint16_t r_unmap[FGD_OPCODE_COUNT]) {")
    lines.append("\tuint8_t m[FGD_OPCODE_COUNT];")
    lines.append("\tuint8_t u[FGD_OPCODE_COUNT];")
    lines.append("\tfgd__omap(m);")
    lines.append("\tfgd__ounmap(u);")
    lines.append("\tfor (int i = 0; i < FGD_OPCODE_COUNT; i++) { r_map[i] = m[i]; r_unmap[i] = u[i]; }")
    lines.append("}")
    lines.append("")

    lines.append("void fgd_pack_pubkey(uint8_t r_pubkey[32]) {")
    lines.append("\tfgd__pubkey(r_pubkey);")
    lines.append("}")
    lines.append("")
    return "\n".join(lines)
